"""Build the portfolio agent's knowledge base from the site itself.

Reads index.html, the case-study pages in work/ and the résumé PDF, splits them
into source-tagged chunks and writes agent/src/knowledge.js for the Worker.
Run from the repo root:  python agent/build_knowledge.py
"""
import json
import pathlib
import re
from html.parser import HTMLParser

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://priyeshdave.github.io"
OUT = ROOT / "agent" / "src" / "knowledge.js"

# Never ship these to the model, even if they appear in a source.
REDACT = [re.compile(r"\+?\d[\d\s-]{8,}\d")]  # phone numbers


class TextGrabber(HTMLParser):
    """Collects visible text, keeping block boundaries as newlines."""

    SKIP = {"script", "style", "noscript", "svg", "head"}
    BLOCK = {"p", "li", "h1", "h2", "h3", "h4", "div", "article", "section", "dt", "dd", "br", "tr"}

    def __init__(self):
        super().__init__()
        self.parts, self.skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in self.SKIP:
            self.skip += 1
        elif tag in self.BLOCK:
            self.parts.append("\n")
        else:
            self.parts.append(" ")

    def handle_endtag(self, tag):
        if tag in self.SKIP and self.skip:
            self.skip -= 1
        elif tag in self.BLOCK:
            self.parts.append("\n")
        else:
            self.parts.append(" ")

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(data)


def clean(text: str) -> str:
    for rx in REDACT:
        text = rx.sub("[redacted]", text)
    lines = [re.sub(r"\s+([.,;:!?])", r"\1", re.sub(r"\s+", " ", ln)).strip() for ln in text.splitlines()]
    out, prev = [], None
    for ln in lines:
        if ln and ln != prev and ln not in {"→", "↗", "✦", "—"}:
            out.append(ln)
        prev = ln
    return "\n".join(out)


def text_of(fragment: str) -> str:
    g = TextGrabber()
    g.feed(fragment)
    return clean("".join(g.parts))


def section(html: str, sid: str) -> str:
    m = re.search(rf'<section id="{sid}"[^>]*>(.*?)</section>', html, re.S)
    return m.group(1) if m else ""


chunks = []


def add(title, url, text):
    text = text.strip()
    if text:
        chunks.append({"id": f"S{len(chunks) + 1}", "title": title, "url": url, "text": text})


# --- Home page -------------------------------------------------------------
home = (ROOT / "index.html").read_text(encoding="utf-8")
add("Portfolio — introduction", f"{SITE}/#hero", text_of(section(home, "hero")))

work = section(home, "work")
for art in re.findall(r'<article class="case">(.*?)</article>', work, re.S):
    title = text_of(re.search(r"<h3>(.*?)</h3>", art, re.S).group(1))
    link = re.search(r'href="(work/[^"]+\.html)"', art)
    url = f"{SITE}/{link.group(1)}" if link else f"{SITE}/#work"
    add(f"Flagship work — {title}", url, text_of(art))

for sid, title in [("ships", "How Priyesh works — principles"),
                   ("stack", "Technical skills"),
                   ("lab", "Open-source projects"),
                   ("experience", "Experience"),
                   ("writing", "Speaking, writing, book, certifications and patents")]:
    add(title, f"{SITE}/#{sid}", text_of(section(home, sid)))

contact = text_of(section(home, "contact"))
add("Contact and profiles", f"{SITE}/#contact", contact)

# --- Case-study pages -------------------------------------------------------
for page in sorted((ROOT / "work").glob("*.html")):
    html = page.read_text(encoding="utf-8")
    main = re.search(r"<main>(.*?)</main>", html, re.S).group(1)
    main = re.sub(r'<nav class="pager".*?</nav>', "", main, flags=re.S)
    title = text_of(re.search(r"<h1[^>]*>(.*?)</h1>", html, re.S).group(1))
    add(f"Case study — {title}", f"{SITE}/work/{page.name}", text_of(main))

# --- Résumé -----------------------------------------------------------------
pdf = ROOT / "Priyesh-Dave-Resume.pdf"
if pdf.exists():
    try:
        from pypdf import PdfReader

        raw = "\n".join(p.extract_text() or "" for p in PdfReader(str(pdf)).pages)
        add("Résumé", f"{SITE}/Priyesh-Dave-Resume.pdf", clean(raw))
    except ImportError:
        print("pypdf not installed — skipping résumé")

total = sum(len(c["text"]) for c in chunks)
OUT.write_text(
    "// Generated by agent/build_knowledge.py — do not edit by hand.\n"
    f"export const KNOWLEDGE = {json.dumps(chunks, ensure_ascii=False, indent=1)};\n",
    encoding="utf-8",
)
print(f"{len(chunks)} chunks, {total:,} characters -> {OUT.relative_to(ROOT)}")
